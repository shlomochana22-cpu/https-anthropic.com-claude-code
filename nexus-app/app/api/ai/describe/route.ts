import { NextResponse } from "next/server";

export const runtime = "edge";

type Body = {
  title?: string;
  genres?: string[];
  category?: string;
  city?: string;
  location?: string;
  time?: string;
  age?: string;
  ageVisible?: boolean;
  tone?: string;
};

/** Local fallback draft — used when no ANTHROPIC_API_KEY is configured. */
function localDraft(b: Body) {
  const g = b.genres?.length ? b.genres.join(", ") : "מוזיקה אלקטרונית";
  const place = b.location || b.city || "המקום החם בעיר";
  const name = b.title || "האירוע";
  const age = b.age && b.ageVisible ? `, כניסה מגיל ${b.age}` : "";
  return (
    `${name} מגיע ל${place} לערב אחד בלתי נשכח. ` +
    `${b.category || "מסיבה"} שכולו ${g} — סאונד עוצמתי, הפקה ויזואלית מטורפת ולהקת DJ's שתחזיק אתכם על רחבת הריקודים עד הזריחה. ` +
    `דלתות נפתחות ב-${b.time || "23:00"}${age}. ` +
    `כמות הכרטיסים מוגבלת — אל תישארו בחוץ. מבטיחים לכם לילה שתזכרו הרבה אחרי שהמוזיקה נגמרת. 🔥`
  );
}

/**
 * AI copywriter for the event description. POST the event fields and get back
 * Hebrew marketing copy generated by Claude. Falls back to a local template
 * when ANTHROPIC_API_KEY is not set, so the feature always works.
 */
export async function POST(req: Request) {
  const body = (await req.json().catch(() => ({}))) as Body;
  const key = process.env.ANTHROPIC_API_KEY;

  if (!key) {
    return NextResponse.json({ text: localDraft(body), source: "local" });
  }

  const facts = [
    body.title && `שם האירוע: ${body.title}`,
    body.category && `סוג: ${body.category}`,
    body.genres?.length && `ז'אנרים: ${body.genres.join(", ")}`,
    (body.location || body.city) && `מיקום: ${[body.location, body.city].filter(Boolean).join(", ")}`,
    body.time && `פתיחת דלתות: ${body.time}`,
    body.age && body.ageVisible && `גיל כניסה: ${body.age}`,
  ]
    .filter(Boolean)
    .join("\n");

  const prompt =
    `אתה קופירייטר של פלטפורמת חיי לילה ישראלית בשם NEXUS. ` +
    `כתוב תיאור שיווקי קצר וסוחף בעברית (2-4 משפטים, 40-70 מילים) לאירוע הבא. ` +
    `טון אנרגטי, צעיר ומזמין, מתאים לרשתות חברתיות. בלי כותרת, בלי נקודות (bullets), בלי האשטגים מוגזמים — אפשר אימוג'י אחד או שניים. ` +
    `החזר רק את הטקסט עצמו.\n\nפרטי האירוע:\n${facts}`;

  try {
    const res = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "x-api-key": key,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model: "claude-haiku-4-5-20251001",
        max_tokens: 400,
        messages: [{ role: "user", content: prompt }],
      }),
    });

    if (!res.ok) {
      return NextResponse.json({ text: localDraft(body), source: "local" });
    }
    const data = await res.json();
    const text: string =
      data?.content?.map((c: { text?: string }) => c.text || "").join("").trim() || localDraft(body);
    return NextResponse.json({ text, source: "ai" });
  } catch {
    return NextResponse.json({ text: localDraft(body), source: "local" });
  }
}
