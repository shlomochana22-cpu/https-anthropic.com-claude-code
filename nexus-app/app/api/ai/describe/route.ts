import { NextResponse } from "next/server";

export const runtime = "edge";

type Action = "write" | "rewrite" | "shorten" | "lengthen";

type Body = {
  title?: string;
  genres?: string[];
  category?: string;
  city?: string;
  location?: string;
  time?: string;
  age?: string;
  ageVisible?: boolean;
  action?: Action;
  current?: string;
};

// Sensible quality default; override with ANTHROPIC_MODEL (e.g. an Opus id).
const MODEL = process.env.ANTHROPIC_MODEL || "claude-sonnet-4-6";

/** Local fallback draft — used when no ANTHROPIC_API_KEY is configured. */
function localDraft(b: Body) {
  const g = b.genres?.length ? b.genres.join(", ") : "מוזיקה אלקטרונית";
  const place = b.location || b.city || "המקום החם בעיר";
  const name = b.title || "האירוע";
  const age = b.age && b.ageVisible ? `, כניסה מגיל ${b.age}` : "";
  const base =
    `${name} מגיע ל${place} לערב אחד בלתי נשכח. ` +
    `${b.category || "מסיבה"} שכולו ${g} — סאונד עוצמתי, הפקה ויזואלית מטורפת ולהקת DJ's שתחזיק אתכם על רחבת הריקודים עד הזריחה. ` +
    `דלתות נפתחות ב-${b.time || "23:00"}${age}. ` +
    `כמות הכרטיסים מוגבלת — אל תישארו בחוץ. מבטיחים לכם לילה שתזכרו הרבה אחרי שהמוזיקה נגמרת. 🔥`;
  // For shorten, return the first sentence-ish chunk of whatever we have.
  if (b.action === "shorten") {
    const src = b.current?.trim() || base;
    return src.split(/(?<=[.!?])\s/).slice(0, 2).join(" ");
  }
  return base;
}

function buildPrompt(b: Body): string {
  const facts = [
    b.title && `שם האירוע: ${b.title}`,
    b.category && `סוג: ${b.category}`,
    b.genres?.length && `ז'אנרים: ${b.genres.join(", ")}`,
    (b.location || b.city) && `מיקום: ${[b.location, b.city].filter(Boolean).join(", ")}`,
    b.time && `פתיחת דלתות: ${b.time}`,
    b.age && b.ageVisible && `גיל כניסה: ${b.age}`,
  ]
    .filter(Boolean)
    .join("\n");

  const persona =
    `אתה קופירייטר של פלטפורמת חיי לילה ישראלית בשם NEXUS. הטון אנרגטי, צעיר ומזמין, מתאים לרשתות חברתיות. ` +
    `בלי כותרת, בלי נקודות (bullets), בלי האשטגים מוגזמים — אפשר אימוג'י אחד או שניים. החזר רק את הטקסט עצמו, בעברית.`;

  const current = b.current?.trim();

  switch (b.action) {
    case "rewrite":
      return `${persona}\nשכתב את התיאור הבא לאירוע בגרסה רעננה ושונה, באותו אורך בערך (2-4 משפטים).\n\nפרטי האירוע:\n${facts}\n\nהתיאור הנוכחי:\n${current}`;
    case "shorten":
      return `${persona}\nקצר את התיאור הבא למשפט אחד או שניים קליטים (עד 25 מילים), בלי לאבד את האנרגיה.\n\nהתיאור הנוכחי:\n${current}`;
    case "lengthen":
      return `${persona}\nהרחב את התיאור הבא ל-4-6 משפטים עשירים יותר (80-120 מילים), הוסף תיאור אווירה וחוויה בלי להמציא עובדות חדשות.\n\nפרטי האירוע:\n${facts}\n\nהתיאור הנוכחי:\n${current}`;
    default:
      return `${persona}\nכתוב תיאור שיווקי קצר וסוחף (2-4 משפטים, 40-70 מילים) לאירוע הבא.\n\nפרטי האירוע:\n${facts}`;
  }
}

/**
 * AI copywriter for the event description. POST the event fields plus an
 * `action` (write | rewrite | shorten | lengthen) and the `current` text,
 * and get back Hebrew marketing copy generated by Claude. Falls back to a
 * local template when ANTHROPIC_API_KEY is not set, so the feature always works.
 */
export async function POST(req: Request) {
  const body = (await req.json().catch(() => ({}))) as Body;
  const key = process.env.ANTHROPIC_API_KEY;

  if (!key) {
    return NextResponse.json({ text: localDraft(body), source: "local" });
  }

  const maxTokens = body.action === "lengthen" ? 700 : body.action === "shorten" ? 200 : 400;

  try {
    const res = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "x-api-key": key,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model: MODEL,
        max_tokens: maxTokens,
        messages: [{ role: "user", content: buildPrompt(body) }],
      }),
    });

    if (!res.ok) {
      return NextResponse.json({ text: localDraft(body), source: "local" });
    }
    const data = await res.json();
    const text: string =
      data?.content?.map((c: { text?: string }) => c.text || "").join("").trim() || localDraft(body);
    return NextResponse.json({ text, source: "ai", model: MODEL });
  } catch {
    return NextResponse.json({ text: localDraft(body), source: "local" });
  }
}
